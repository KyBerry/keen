"""HTML report emitter for Keen runs.

Produces a single self-contained ``report.html`` next to ``report.json`` and
``summary.md``. The HTML embeds every artifact (screenshots, annotated
overlays, per-component crops, token palette swatches) as base64 data URIs so
the file can be shared without any side-car directory.

Constraints:
  * Stdlib only — no Jinja2, no markdown library, no Pillow tricks beyond
    what report.py already uses.
  * No external HTTP requests in the rendered HTML (no CDN, no remote fonts).
  * All untrusted strings flow through ``html.escape`` before substitution.
  * The HTML must pass the same accessibility predicates Keen emits
    against any page (contrast >= 4.5:1, focus rings visible, landmarks).

The renderer is intentionally tolerant: missing artifacts (no screenshots,
no tokens, no captures) degrade to empty-state messaging rather than crash.
"""

from __future__ import annotations

import base64
import html
import logging
import re
from collections.abc import Iterable
from datetime import datetime, timezone
from pathlib import Path
from string import Template
from typing import Any

logger = logging.getLogger("keen.report.html")

# Severity ranking used for sortable table data-sort-value.
_SEVERITY_RANK = {"P0": 0, "P1": 1, "P2": 2}
_MAX_EMBED_IMAGE_BYTES = 8 * 1024 * 1024

_TEMPLATE_PATH = Path(__file__).parent / "templates" / "report.html.tmpl"


# ---------------------------------------------------------------------------
# Tiny markdown subset → HTML.
# ---------------------------------------------------------------------------


_BOLD_RE = re.compile(r"\*\*(.+?)\*\*", re.DOTALL)
_ITALIC_RE = re.compile(r"(?<![A-Za-z0-9_])_([^_\n]+?)_(?![A-Za-z0-9_])")
_CODE_RE = re.compile(r"`([^`\n]+?)`")
_LINK_RE = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)")
_UL_RE = re.compile(r"^- (.*)$")
_HEADING_RE = re.compile(r"^(#{1,6})\s+(.*)$")
_TABLE_ROW_RE = re.compile(r"^\|(.+)\|\s*$")
_TABLE_ALIGN_RE = re.compile(r"^\|[\s\-:|]+\|\s*$")


def _safe_link_url(raw: str) -> str:
    """Render ``[text](url)``-style links only for safe schemes.

    The summary.md is generated by us, but defense-in-depth: even if some
    upstream module ever embeds a hostile URL, only http/https/mailto/relative
    paths survive into the HTML; everything else collapses to ``#``.
    """
    lowered = raw.strip().lower()
    if lowered.startswith(("http://", "https://", "mailto:", "/", "#", "./", "../")):
        return html.escape(raw, quote=True)
    return "#"


def _apply_inline(text: str) -> str:
    """Apply inline markdown (bold/italic/code/link) to a pre-escaped string."""
    text = _CODE_RE.sub(lambda m: f"<code>{m.group(1)}</code>", text)
    # Render links AFTER code so backticks inside link text aren't garbled.
    text = _LINK_RE.sub(
        lambda m: f'<a href="{_safe_link_url(m.group(2))}">{m.group(1)}</a>',
        text,
    )
    text = _BOLD_RE.sub(lambda m: f"<strong>{m.group(1)}</strong>", text)
    text = _ITALIC_RE.sub(lambda m: f"<em>{m.group(1)}</em>", text)
    return text


def md_to_html(src: str, *, heading_offset: int = 0) -> str:
    r"""Render a narrow subset of markdown to HTML.

    Covers: ATX headings (# ## ### #### ##### ######), paragraphs separated by
    blank lines, ``**bold**``, ``_italic_``, ``\`inline code\```, fenced code
    blocks (```), bullet lists (``- ``), GFM-style tables, and
    ``[link text](url)`` inline links.

    Not a full CommonMark implementation. The summary.md is generated by us,
    so we control the input shape — see render_summary in report.py.

    Input is HTML-escaped via ``html.escape`` so no arbitrary HTML passes
    through (defense against any pre-injected markdown that survived
    ``_sanitize.py``).

    ``heading_offset`` shifts every heading down by N levels (clamped to h6) so
    the embedded markdown doesn't compete with the page's own ``<h1>``. Set to
    1 when injecting summary.md into a section that already has its own
    ``<h2>`` heading.
    """
    if not src:
        return ""

    # Escape the whole input first so any < > & in the source becomes inert.
    # Inline rules then re-inject only the specific tags we want.
    escaped = html.escape(src, quote=False)
    lines = escaped.split("\n")

    out: list[str] = []
    in_code = False
    code_buf: list[str] = []
    in_list = False
    in_para: list[str] = []
    in_table = False
    table_buf: list[list[str]] = []
    table_aligns: list[str] = []
    table_header_done = False

    def flush_para() -> None:
        nonlocal in_para
        if in_para:
            text = " ".join(in_para).strip()
            if text:
                out.append(f"<p>{_apply_inline(text)}</p>")
            in_para = []

    def flush_list() -> None:
        nonlocal in_list
        if in_list:
            out.append("</ul>")
            in_list = False

    def flush_table() -> None:
        nonlocal in_table, table_buf, table_aligns, table_header_done
        if in_table and table_buf:
            out.append("<table>")
            if table_header_done and table_buf:
                # First row is header.
                out.append("<thead><tr>")
                for cell in table_buf[0]:
                    out.append(f"<th>{_apply_inline(cell.strip())}</th>")
                out.append("</tr></thead>")
                body = table_buf[1:]
            else:
                body = table_buf
            if body:
                out.append("<tbody>")
                for row in body:
                    out.append("<tr>")
                    for cell in row:
                        out.append(f"<td>{_apply_inline(cell.strip())}</td>")
                    out.append("</tr>")
                out.append("</tbody>")
            out.append("</table>")
        in_table = False
        table_buf = []
        table_aligns = []
        table_header_done = False

    def flush_all() -> None:
        flush_para()
        flush_list()
        flush_table()

    for raw_line in lines:
        line = raw_line.rstrip()

        # Fenced code blocks: ``` start/end.
        if line.startswith("```"):
            if in_code:
                out.append("<pre><code>" + "\n".join(code_buf) + "</code></pre>")
                code_buf = []
                in_code = False
            else:
                flush_all()
                in_code = True
            continue
        if in_code:
            code_buf.append(line)
            continue

        # Tables (GFM).
        m_row = _TABLE_ROW_RE.match(line)
        m_align = _TABLE_ALIGN_RE.match(line)
        if m_row and m_align and in_table and len(table_buf) == 1:
            # Alignment row right after a header row — mark header as done.
            table_aligns = [c.strip() for c in m_row.group(1).split("|")]
            table_header_done = True
            continue
        if m_row:
            if not in_table:
                flush_all()
                in_table = True
            cells = list(line.strip("|").split("|"))
            table_buf.append(cells)
            continue
        if in_table:
            flush_table()

        # Headings.
        m_h = _HEADING_RE.match(line)
        if m_h:
            flush_all()
            level = min(6, len(m_h.group(1)) + heading_offset)
            content = _apply_inline(m_h.group(2))
            out.append(f"<h{level}>{content}</h{level}>")
            continue

        # Bullet list.
        m_ul = _UL_RE.match(line)
        if m_ul:
            flush_para()
            if not in_list:
                out.append("<ul>")
                in_list = True
            out.append(f"<li>{_apply_inline(m_ul.group(1))}</li>")
            continue

        # Horizontal rule.
        if line.strip() in {"---", "***", "___"}:
            flush_all()
            out.append("<hr>")
            continue

        # Blank line ends paragraphs/lists.
        if not line.strip():
            flush_para()
            flush_list()
            flush_table()
            continue

        # Default: paragraph.
        flush_list()
        in_para.append(line.strip())

    # End of input — close any open container.
    if in_code:
        out.append("<pre><code>" + "\n".join(code_buf) + "</code></pre>")
    flush_all()
    return "\n".join(out)


