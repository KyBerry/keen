def _encode_image(path: Path) -> str | None:
    """Read PNG at ``path``, return ``data:image/png;base64,...`` or None.

    Defensive: large or unreadable files return ``None`` so the renderer can
    fall back to an empty-state placeholder.
    """
    try:
        size = path.stat().st_size
        if size > _MAX_EMBED_IMAGE_BYTES:
            logger.warning(
                "refusing to embed %s: %d bytes exceeds the %d-byte limit; use linked images",
                path,
                size,
                _MAX_EMBED_IMAGE_BYTES,
            )
            return None
        data = path.read_bytes()
    except OSError as e:
        logger.warning("could not read %s for embedding: %s", path, e)
        return None
    encoded = base64.b64encode(data).decode("ascii")
    # Crude content-type sniffing — all our screenshots are PNG, but be robust.
    if data[:4] == b"\x89PNG":
        ct = "image/png"
    elif data[:3] in (b"\xff\xd8\xff", b"GIF"):
        ct = "image/jpeg" if data[:3] == b"\xff\xd8\xff" else "image/gif"
    elif data[:6] in (b"RIFF\x00\x00", b"WEBPVP"):
        ct = "image/webp"
    else:
        ct = "image/png"
    return f"data:{ct};base64,{encoded}"


def _image_src(captures_dir: Path, rel_path: str | None, *, link_images: bool) -> str | None:
    """Resolve a relative image path into either a base64 data URI or a
    sandboxed relative-path string.

    ``rel_path`` may be ``None`` or refer to a file that no longer exists; both
    cases return ``None`` so the caller can omit the figure entirely.
    """
    if not rel_path:
        return None
    captures_root = captures_dir.resolve()
    target = (captures_dir / rel_path).resolve()
    try:
        target.relative_to(captures_root)
    except ValueError:
        logger.warning("blocked path traversal: %s outside %s", target, captures_root)
        return None
    if not target.exists():
        return None
    if link_images:
        # Use the relative path verbatim (it's already constrained to
        # captures_root). Escape for HTML attribute safety.
        return html.escape(rel_path, quote=True)
    return _encode_image(target)


