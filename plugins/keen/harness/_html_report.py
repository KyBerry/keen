def _redacted_url_for_display(captures: list[dict[str, Any]]) -> str:
    """Pick the first capture's URL, already redacted by sanitize_capture_meta."""
    for cap in captures:
        url = cap.get("url")
        if url:
            return str(url)
    return ""


def _display_title(captures: list[dict[str, Any]]) -> str:
    """Prefer the document title; shorten local-file fallbacks to a filename."""
    for cap in captures:
        title = str(cap.get("title", "") or "").strip()
        if title:
            return title
    raw = _redacted_url_for_display(captures)
    if raw.startswith("file://"):
        return Path(raw.removeprefix("file://")).name or "Local interface"
    return raw or "Keen review"


def _render_verdict(
    report: dict[str, Any],
    *,
    captures: list[dict[str, Any]],
    summary_md: str,
) -> str:
    """Render a decision-first overview without repeating later evidence chapters."""
    score = report.get("score") or {}
    if not score and summary_md:
        return md_to_html(summary_md, heading_offset=2)

    counts = score.get("counts") or {}

    def count(severity: str) -> int:
        value = counts.get(severity, 0)
        return int(value) if isinstance(value, (int, float)) else 0

    p0, p1, p2 = count("P0"), count("P1"), count("P2")
    coverage = report.get("coverage") or {}
    complete = bool(coverage.get("complete", True))
    capture_status = "complete" if complete else "provisional"
    total = p0 + p1 + p2
    signal_copy = (
        f"The harness found {total} deterministic candidate signal{'s' if total != 1 else ''}. "
        "They locate evidence; they do not decide whether the product is beautiful, coherent, or ready."
    )
    guidance = (
        "Use project direction and rendered context to assign user impact and final priority."
    )
    return (
        '<div class="verdict-lead">'
        '<p class="verdict-kicker">Automated evidence</p>'
        f'<p class="verdict-copy">{html.escape(signal_copy)}</p>'
        "</div>"
        '<dl class="verdict-facts">'
        f"<div><dt>P0 candidates</dt><dd>{p0}</dd></div>"
        f"<div><dt>P1 candidates</dt><dd>{p1}</dd></div>"
        f"<div><dt>P2 candidates</dt><dd>{p2}</dd></div>"
        f"<div><dt>Capture coverage</dt><dd>{len(captures)} / {html.escape(capture_status)}</dd></div>"
        "</dl>"
        f'<p class="verdict-guidance">{html.escape(guidance)}</p>'
        '<a class="verdict-link" href="#findings">Inspect candidate evidence <span aria-hidden="true">→</span></a>'
    )


def _iso_now() -> str:
    """Return current UTC ISO-8601 timestamp suitable for the report header."""
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def render_report(
    report: dict[str, Any],
    *,
    captures_dir: Path,
    summary_md: str,
    link_images: bool = False,
) -> str:
    """Render the full ``report.html`` string.

    Parameters
    ----------
    report:
        The dict returned by ``report.compose`` (same shape as ``report.json``).
    captures_dir:
        The directory the run wrote into. Image paths are resolved relative to
        it; traversal outside is blocked.
    summary_md:
        The summary as produced by ``report.render_summary`` — gets rendered
        through the tiny markdown converter into ``<div class="summary-block">``.
    link_images:
        When True, image ``src`` attributes are emitted as relative paths
        (e.g. ``./screens/desktop-default.png``). When False (default), images
        are inlined as base64 ``data:`` URIs so ``report.html`` is fully
        self-contained.
    """
    captures = list(report.get("captures") or [])
    score = report.get("score") or {}
    title = _display_title(captures)

    summary_html = _render_verdict(report, captures=captures, summary_md=summary_md)
    findings_html = _render_findings_table(report.get("top_findings") or [])
    gallery_html = _render_gallery(
        captures,
        dict(report.get("annotated_overviews") or {}),
        dict(report.get("annotations") or {}),
        captures_dir,
        link_images=link_images,
    )
    components_html = _render_components(
        list(report.get("components") or []),
        list(report.get("top_findings") or []),
        captures_dir,
        link_images=link_images,
    )
    tokens_html = _render_tokens(dict(report.get("tokens") or {}))

    target_system = report.get("target_system") or "(none)"
    grade = score.get("grade") or "?"
    damage_val = score.get("score")
    damage = "—" if damage_val is None else f"{damage_val}"

    template_text = _TEMPLATE_PATH.read_text(encoding="utf-8")
    tmpl = Template(template_text)
    return tmpl.substitute(
        title=html.escape(str(title)),
        captured_at=html.escape(_iso_now()),
        grade=html.escape(str(grade)),
        damage=html.escape(damage),
        target_system=html.escape(str(target_system)),
        summary_html=summary_html,
        findings_table_html=findings_html,
        gallery_html=gallery_html,
        components_html=components_html,
        tokens_html=tokens_html,
    )


def write_report(
    report: dict[str, Any],
    captures_dir: Path,
    summary_md: str,
    *,
    link_images: bool = False,
) -> Path:
    """Render and write ``report.html`` into ``captures_dir``.

    Returns the path written. Errors are logged and swallowed: the HTML report
    is a convenience; if rendering blows up, the run still produces JSON and
    markdown.
    """
    out_path = Path(captures_dir) / "report.html"
    try:
        html_str = render_report(
            report,
            captures_dir=Path(captures_dir),
            summary_md=summary_md,
            link_images=link_images,
        )
        out_path.write_text(html_str, encoding="utf-8")
    except Exception:
        logger.exception("html report generation failed; report.html not written")
        # Best-effort: do not propagate. The caller already has JSON/MD.
        return out_path
    return out_path
