def _render_findings_table(top_findings: Iterable[dict[str, Any]]) -> str:
    findings = list(top_findings)
    if not findings:
        return '<p class="empty" role="status">No findings to display.</p>'
    rows: list[str] = []
    for f in findings:
        finding_id = str(f.get("finding_id") or "")
        annotation_id = str(f.get("annotation_id") or "")
        sev = str(f.get("severity", "P2"))
        sev_rank = _SEVERITY_RANK.get(sev, 9)
        pid = str(f.get("predicate_id", ""))
        kind = str(f.get("component_kind", ""))
        viewport = str(f.get("viewport", "") or "")
        state = str(f.get("state", "") or "")
        msg = str(f.get("message", ""))
        crop = str(f.get("crop_path", "") or "")
        component_idx = f.get("component_index")
        target_id = (
            _component_anchor(viewport, state, component_idx) if component_idx is not None else None
        )
        loc = f"{viewport}/{state}" if viewport or state else ""
        link_html = ""
        if annotation_id:
            link_html += (
                f' <a class="evidence-link" href="#annotation-{html.escape(annotation_id, quote=True)}">'
                f"locate {html.escape(annotation_id)}</a>"
            )
        if target_id:
            # Visible label "view" must appear in the accessible name (WCAG 2.5.3
            # Label in Name). Putting "view" first satisfies the speech-input
            # check and the longer phrase still gives context to screen readers.
            link_html += (
                f' <a class="row-link" href="#{html.escape(target_id, quote=True)}" '
                f'aria-label="view {html.escape(kind)} component">view</a>'
            )
        elif crop:
            link_html += f" <code>{html.escape(crop)}</code>"
        row_id = f' id="{html.escape(finding_id, quote=True)}"' if finding_id else ""
        rows.append(
            f"<tr{row_id}>"
            f'<td data-sort-value="{sev_rank}">'
            f'<span class="badge badge-{html.escape(sev)}" aria-label="severity {html.escape(sev)}">{html.escape(sev)}</span>'
            "</td>"
            f'<td data-sort-value="{html.escape(pid)}"><code>{html.escape(pid)}</code></td>'
            f'<td data-sort-value="{html.escape(kind)}">{html.escape(kind)}</td>'
            f'<td data-sort-value="{html.escape(loc)}">{html.escape(loc)}</td>'
            f"<td>{html.escape(msg)}{link_html}</td>"
            "</tr>"
        )
    head = (
        "<thead><tr>"
        '<th data-sort-type="number" scope="col"><button type="button" class="sort-button">'
        'Severity<span class="sort-indicator" aria-hidden="true"></span></button></th>'
        '<th scope="col"><button type="button" class="sort-button">'
        'Predicate<span class="sort-indicator" aria-hidden="true"></span></button></th>'
        '<th scope="col"><button type="button" class="sort-button">'
        'Component<span class="sort-indicator" aria-hidden="true"></span></button></th>'
        '<th scope="col"><button type="button" class="sort-button">'
        'Location<span class="sort-indicator" aria-hidden="true"></span></button></th>'
        '<th scope="col"><button type="button" class="sort-button">'
        'Message<span class="sort-indicator" aria-hidden="true"></span></button></th>'
        "</tr></thead>"
    )
    body = "<tbody>" + "".join(rows) + "</tbody>"
    return f'<table class="findings" aria-label="Candidate findings, sortable">{head}{body}</table>'


def _render_gallery(
    captures: list[dict[str, Any]],
    annotated: dict[str, str],
    annotations: dict[str, list[dict[str, Any]]],
    captures_dir: Path,
    *,
    link_images: bool,
) -> str:
    if not captures:
        return '<p class="empty" role="status">No screenshots captured.</p>'
    figs: list[str] = []
    for idx, cap in enumerate(captures):
        viewport = str(cap.get("viewport", "") or "")
        state = str(cap.get("state", "") or "")
        screen_rel = cap.get("screen_path")
        raw_src = _image_src(captures_dir, screen_rel, link_images=link_images)
        # Look up annotated by stem.
        annot_src: str | None = None
        if screen_rel:
            stem = Path(screen_rel).stem
            annot_rel = annotated.get(stem)
            if annot_rel:
                annot_src = _image_src(captures_dir, annot_rel, link_images=link_images)
        else:
            stem = ""
        marker_entries = list(annotations.get(stem) or [])

        if not raw_src and not annot_src:
            continue

        manual = cap.get("manual_review_needed", False)
        manual_tag = (
            ' <span class="badge badge-P1" aria-label="Manual review needed">manual</span>'
            if manual
            else ""
        )
        wrap_id = f"shot-{idx}"
        figure_parts: list[str] = []
        figure_parts.append(f'<figure id="screen-{idx}">')
        figure_parts.append(
            "<figcaption>"
            '<span class="screen-label">'
            f'<span class="vp-label">{html.escape(viewport)}'
            f"{(' / ' + html.escape(state)) if state else ''}{manual_tag}</span>"
            f'<span class="screen-count">{len(marker_entries)} mapped priorit'
            f"{'y' if len(marker_entries) == 1 else 'ies'}</span>"
            "</span>"
            '<span class="screen-actions">'
        )
        if annot_src and raw_src:
            figure_parts.append(
                f'<button type="button" class="toggle-btn" data-toggle-target="{wrap_id}" '
                'aria-pressed="false">Show evidence map</button>'
            )
        figure_parts.append(
            f'<button type="button" class="inspect-btn" data-inspect-target="{wrap_id}" '
            'aria-pressed="false">Inspect detail</button>'
        )
        if raw_src:
            figure_parts.append(
                f'<a class="full-image-link" href="{raw_src}" target="_blank" '
                'rel="noopener">Open image</a>'
            )
        figure_parts.append("</span>")
        figure_parts.append("</figcaption>")
        figure_parts.append(f'<div class="img-wrap" id="{wrap_id}">')
        # Default visible: raw screenshot; annotated hidden until toggled.
        if raw_src:
            figure_parts.append(
                f'<img data-variant="raw" src="{raw_src}" '
                f'alt="screenshot of {html.escape(viewport)} {html.escape(state)}" loading="lazy">'
            )
        if annot_src:
            figure_parts.append(
                f'<img data-variant="annotated" src="{annot_src}" '
                f'alt="annotated screenshot of {html.escape(viewport)} {html.escape(state)} '
                'with bounding boxes" hidden loading="lazy">'
            )
        figure_parts.append("</div>")
        if marker_entries:
            figure_parts.append('<ol class="annotation-key" aria-label="Mapped priority findings">')
            for marker in marker_entries:
                annotation_id = str(marker.get("id") or "")
                severity = str(marker.get("severity") or "P1")
                predicates = ", ".join(str(value) for value in (marker.get("predicate_ids") or []))
                message = str(marker.get("message") or "")
                finding_ids = marker.get("finding_ids") or []
                href = f"#{finding_ids[0]}" if finding_ids else "#findings"
                figure_parts.append(
                    f'<li id="annotation-{html.escape(annotation_id, quote=True)}">'
                    f'<a href="{html.escape(href, quote=True)}">'
                    f'<span class="annotation-marker badge-{html.escape(severity)}">'
                    f"{html.escape(annotation_id)}</span>"
                    '<span class="annotation-copy">'
                    f"<strong>{html.escape(severity)} · {html.escape(predicates)}</strong>"
                    f"<span>{html.escape(message)}</span>"
                    "</span></a></li>"
                )
            figure_parts.append("</ol>")
        figure_parts.append("</figure>")
        figs.append("".join(figure_parts))
    if not figs:
        return '<p class="empty" role="status">No screenshots could be embedded.</p>'
    return '<div class="gallery">' + "".join(figs) + "</div>"


def _render_components(
    components: list[dict[str, Any]],
    top_findings: list[dict[str, Any]],
    captures_dir: Path,
    *,
    link_images: bool,
    limit: int = 24,
) -> str:
    flagged = [c for c in components if c.get("findings")]
    if not flagged:
        return '<p class="empty" role="status">No flagged components.</p>'

    by_key = {
        (str(component.get("capture_path") or ""), component.get("index")): component
        for component in flagged
    }
    selected: list[dict[str, Any]] = []
    selected_keys: set[tuple[str, Any]] = set()

    def add(component: dict[str, Any]) -> None:
        key = (str(component.get("capture_path") or ""), component.get("index"))
        if key not in selected_keys and len(selected) < limit:
            selected.append(component)
            selected_keys.add(key)

    # Every component linked from the bounded findings table must exist in the
    # evidence section. This keeps table links truthful while avoiding a
    # hundred-card appendix dominated by one repeated heuristic.
    for finding in top_findings:
        key = (
            str(finding.get("capture_path") or ""),
            finding.get("component_index"),
        )
        component = by_key.get(key)
        if component is not None:
            add(component)

    severity_rank = {"P0": 0, "P1": 1, "P2": 2}

    def card_rank(component: dict[str, Any]) -> tuple[int, str, str, int]:
        findings = component.get("findings") or []
        best = min(
            (severity_rank.get(str(finding.get("severity") or "P2"), 9) for finding in findings),
            default=9,
        )
        predicates = sorted(str(finding.get("predicate_id") or "") for finding in findings)
        return (
            best,
            predicates[0] if predicates else "",
            str(component.get("capture_path") or ""),
            int(component.get("index") or 0),
        )

    predicate_counts: dict[str, int] = {}
    for component in sorted(flagged, key=card_rank):
        if len(selected) >= limit:
            break
        predicates = {
            str(finding.get("predicate_id") or "") for finding in (component.get("findings") or [])
        }
        if predicates and all(predicate_counts.get(pid, 0) >= 3 for pid in predicates):
            continue
        before = len(selected)
        add(component)
        if len(selected) > before:
            for predicate_id in predicates:
                predicate_counts[predicate_id] = predicate_counts.get(predicate_id, 0) + 1

    cards: list[str] = []
    for c in selected:
        idx = c.get("index")
        kind = str(c.get("component_kind", ""))
        viewport = str(c.get("viewport", "") or "")
        state = str(c.get("state", "") or "")
        box = c.get("box", {}) or {}
        crop_rel = c.get("crop_path")
        crop_src = _image_src(captures_dir, crop_rel, link_images=link_images)
        anchor = _component_anchor(viewport, state, idx) if idx is not None else ""
        bx, by = box.get("x", 0), box.get("y", 0)
        bw, bh = box.get("w", 0), box.get("h", 0)
        try:
            bx_s = f"{float(bx):.0f}"
            by_s = f"{float(by):.0f}"
            bw_s = f"{float(bw):.0f}"
            bh_s = f"{float(bh):.0f}"
        except (TypeError, ValueError):
            bx_s = by_s = bw_s = bh_s = "?"
        findings_items: list[str] = []
        for f in c.get("findings", []) or []:
            sev = str(f.get("severity", "P2"))
            msg = str(f.get("message", ""))
            pid = str(f.get("predicate_id", ""))
            findings_items.append(
                f'<li><span class="badge badge-{html.escape(sev)}" '
                f'aria-label="severity {html.escape(sev)}">{html.escape(sev)}</span> '
                f"<code>{html.escape(pid)}</code> — {html.escape(msg)}</li>"
            )
        img_html = ""
        if crop_src:
            img_html = (
                f'<img src="{crop_src}" alt="crop of {html.escape(kind)} component" loading="lazy">'
            )
        anchor_attr = f' id="{html.escape(anchor, quote=True)}"' if anchor else ""
        card = (
            f'<article class="component-card"{anchor_attr}>'
            f"{img_html}"
            f'<div class="ckind">{html.escape(kind)}</div>'
            f'<div class="cbox">{html.escape(viewport)}/{html.escape(state)} '
            f"@ {bx_s},{by_s} {bw_s}×{bh_s}</div>"
            f'<ul class="cfind">{"".join(findings_items)}</ul>'
            "</article>"
        )
        cards.append(card)
    note = (
        f'<p class="evidence-summary">Showing {len(selected)} representative components '
        f"from {len(flagged)} flagged. The complete inventory remains in "
        "<code>report.json</code>.</p>"
        if len(selected) < len(flagged)
        else ""
    )
    return note + '<div class="component-list">' + "".join(cards) + "</div>"


def _component_anchor(viewport: str, state: str, index: Any) -> str:
    """Return a capture-scoped, HTML-safe anchor for a component."""
    raw = f"component-{viewport}-{state}-{index}".lower()
    return re.sub(r"[^a-z0-9_-]+", "-", raw).strip("-")


def _render_tokens(tokens: dict[str, Any]) -> str:
    if not tokens:
        return '<p class="empty" role="status">No tokens extracted.</p>'
    parts: list[str] = []

    colors = tokens.get("colors") or {}
    fg = colors.get("foreground") or []
    bg = colors.get("background") or []

    def color_swatches(label: str, items: list[dict[str, Any]]) -> str:
        if not items:
            return ""
        swatches: list[str] = []
        for entry in items[:16]:
            val = str(entry.get("value", "") or "")
            count = entry.get("count", 0)
            # Only inject color values that look safe (rgb()/rgba()/#hex/named).
            safe = bool(
                re.match(
                    r"^(?:#[0-9a-fA-F]{3,8}|rgb\(\s*[\d., %]+\s*\)|rgba\(\s*[\d., %]+\s*\)|[a-zA-Z]+)$",
                    val.strip(),
                )
            )
            chip_style = f"background:{val}" if safe and val else "background:transparent"
            swatches.append(
                '<div class="swatch">'
                f'<span class="chip" style="{html.escape(chip_style, quote=True)}" aria-hidden="true"></span>'
                f"<span>{html.escape(val)}</span>"
                f'<span class="count">x{int(count) if isinstance(count, (int, float)) else 0}</span>'
                "</div>"
            )
        return f'<h3>{html.escape(label)}</h3><div class="swatches">{"".join(swatches)}</div>'

    parts.append(color_swatches("Foreground colors", fg))
    parts.append(color_swatches("Background colors", bg))

    # Type scale.
    type_block = tokens.get("type") or {}
    sizes = type_block.get("sizes_px") or []
    if sizes:
        rows: list[str] = []
        for entry in sizes[:12]:
            val = entry.get("value")
            count = entry.get("count", 0)
            if not isinstance(val, (int, float, str)):
                continue
            try:
                px = float(val)
            except (TypeError, ValueError):
                continue
            # Cap rendered sample at 48px so wild outliers don't break layout.
            sample_size = min(max(px, 10), 48)
            rows.append(
                '<div class="scale-row">'
                f'<span class="sample" style="font-size:{sample_size:.0f}px">Aa</span>'
                f'<span class="meta">{px:.0f}px '
                f'<span class="count">x{int(count) if isinstance(count, (int, float)) else 0}</span></span>'
                "</div>"
            )
        if rows:
            parts.append("<h3>Type scale</h3>" + "".join(rows))

    # Spacing + radii.
    shape = tokens.get("shape") or {}
    radii = shape.get("border_radii_px") or []
    spacing = (tokens.get("spacing") or {}).get("values_px") or []

    def numeric_list(label: str, items: list[dict[str, Any]]) -> str:
        if not items:
            return ""
        swatches: list[str] = []
        for entry in items[:24]:
            val = entry.get("value")
            count = entry.get("count", 0)
            if not isinstance(val, (int, float, str)):
                continue
            try:
                px = float(val)
            except (TypeError, ValueError):
                continue
            swatches.append(
                '<div class="swatch">'
                f"<span>{px:.0f}px</span>"
                f'<span class="count">x{int(count) if isinstance(count, (int, float)) else 0}</span>'
                "</div>"
            )
        return f'<h3>{html.escape(label)}</h3><div class="swatches">{"".join(swatches)}</div>'

    parts.append(numeric_list("Border radii", radii))
    parts.append(numeric_list("Spacing values", spacing))

    diag = tokens.get("diagnostics") or {}
    if diag:
        diagnostic_rows: list[str] = []
        for k, v in diag.items():
            diagnostic_rows.append(f"<dt>{html.escape(str(k))}</dt><dd>{html.escape(str(v))}</dd>")
        parts.append(
            "<h3>Diagnostics</h3>" + f'<dl class="kv-grid">{"".join(diagnostic_rows)}</dl>'
        )

    rendered = "".join(p for p in parts if p)
    if not rendered:
        return '<p class="empty" role="status">No tokens extracted.</p>'
    return rendered


